function buildWhy(q) {
  const pts = q.points || [];
  const stories = STORIES[q.id];
  const lines = [];
  for (let i = 0; i < pts.length; i++) {
    const n = i + 1;
    let story = stories && stories[i];
    if (!story) {
      story =
        "这些年落到这句上的具体事：对照「" +
        String(pts[i] || "").replace(/[。．.]+$/, "") +
        "」想一想身边/时政里对应的画面，再背更贴。";
    }
    lines.push(n + ". " + story);
  }
  return lines.join("\n\n");
}

